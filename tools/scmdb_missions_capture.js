/* Public rendered DOM only. Optional batches click existing cards and detail tabs. */
(() => {
  "use strict";
  if (location.hostname !== "scmdb.net") { alert("请先打开 https://scmdb.net/ 的任务页面。"); return; }
  if (window.__SCMDB_MISSIONS_CAPTURE__) { window.__SCMDB_MISSIONS_CAPTURE__.show(); return; }

  const records = new Map();
  const cardById = new Map();
  let paused = false;
  let timer;
  let lastError = "";
  let automation = null;
  let disposed = false;
  let storageStatus = "尚未保存进度";
  let checkpointBusy = false;
  const completed = new Set();
  const runs = [];
  const startedAt = new Date().toISOString();
  const compact = (value) => String(value || "").replace(/\r/g, "").split("\n").map((line) => line.trim()).filter(Boolean).join("\n");
  const text = (node) => compact(node?.innerText);
  const visible = (node) => !!node && node.getClientRects().length > 0 && getComputedStyle(node).visibility !== "hidden";
  // Match the public link identifier generated by SCMDB (djb2, base36).
  function publicId(debugName) {
    let value = 5381;
    for (let index = 0; index < debugName.length; index += 1) value = ((value << 5) + value + debugName.charCodeAt(index)) | 0;
    return (value >>> 0).toString(36);
  }
  function identity(url) {
    const parsed = new URL(url, location.href);
    return { mission_id: parsed.searchParams.get("m"), channel: parsed.searchParams.get("channel") || "live" };
  }
  function record(url, title, debugName = "") {
    const id = identity(url);
    // Never merge distinct tasks by their display title.
    if (!id.mission_id) return null;
    const key = `${id.channel}:${id.mission_id}`;
    if (!records.has(key)) records.set(key, { ...id, source_url: new URL(url, location.href).href, title, debug_name: debugName, first_seen_at: new Date().toISOString(), list_snapshots: [], detail_snapshots: [] });
    const item = records.get(key);
    if (title) item.title = title;
    if (debugName) item.debug_name = debugName;
    return item;
  }
  function appendUnique(items, snapshot) {
    const signature = JSON.stringify(snapshot);
    if (!items.some((item) => item.signature === signature)) items.push({ signature, value: { ...snapshot, captured_at: new Date().toISOString() } });
  }
  function linksWithin(root) {
    return [...root.querySelectorAll("a[href]")].filter(visible).map((link) => ({ text: text(link), url: link.href })).filter((link) => /^https?:/.test(link.url));
  }
  function tabEntries(modal) {
    const tabs = [...modal.querySelectorAll(".detail-tab")];
    return tabs.map((element, index) => {
      const label = text(element);
      const normalized = label.toLowerCase();
      const aliases = { overview: "overview", "概览": "overview", "总览": "overview", combat: "combat", "战斗": "combat", requirements: "requirements", "要求": "requirements", "接取条件": "requirements", calculator: "calculator", "计算器": "calculator", community: "community", "社区": "community" };
      // Current SCMDB always ends with Calculator, Community; Combat is optional.
      // Only use this positional fallback for the verified four/five-tab layout.
      const layout = tabs.length === 4 ? ["overview", "requirements", "calculator", "community"] : tabs.length === 5 ? ["overview", "combat", "requirements", "calculator", "community"] : [];
      return { element, label, key: aliases[normalized] || layout[index] || "unknown" };
    });
  }
  function publicTab(key) { return ["overview", "combat", "requirements", "calculator"].includes(key); }
  function currentModal() { return [...document.querySelectorAll(".detail-modal")].find(visible); }
  function modalId(modal) {
    const debugName = modal?.querySelector(".detail-title")?.getAttribute("title")?.split("\n")[0];
    return debugName ? publicId(debugName) : null;
  }
  function calculatorBasis(body) {
    if (!body) return null;
    return {
      reward_fields: [...body.querySelectorAll(".missions-calc-info")].filter(visible).map((group) => ({
        labels: [...group.querySelectorAll(".calc-label")].map(text),
        values: [...group.querySelectorAll(".calc-value")].map(text),
      })),
      rank_tables: [...body.querySelectorAll(".calc-table")].filter(visible).map((table) => ({
        caption: text(table.querySelector("caption")),
        ranks: [...table.querySelectorAll("tbody tr")].map((row) => {
          const cells = [...row.querySelectorAll("td")];
          return { rank: text(cells[0]), xp_to_fill_text: text(cells[1]), row_class: row.getAttribute("class") || "" };
        }),
      })),
      rules: [...body.querySelectorAll('[class*="calc-note"], .calc-scope-divergence')].filter(visible).map(text),
      note: "XP to fill is the displayed per-rank delta, not a cumulative threshold. No mission-count column or player inputs collected. Sharing exceptions require interpreting the displayed rules.",
    };
  }
  function capture(detailsOnly = false) {
    if (paused) return;
    try {
      if (!detailsOnly) document.querySelectorAll("a.contract-card[href]").forEach((card) => {
        if (!visible(card)) return;
        const id = identity(card.href);
        cardById.set(`${id.channel}:${id.mission_id}`, card);
        const item = record(card.href, text(card.querySelector(".card-title")));
        if (item) appendUnique(item.list_snapshots, { raw_text: text(card), tooltips: [...card.querySelectorAll("[title]")].filter(visible).map((node) => node.getAttribute("title")) });
      });
      document.querySelectorAll(".detail-modal").forEach((modal) => {
        if (!visible(modal)) return;
        const title = modal.querySelector(".detail-title");
        const debugName = title?.getAttribute("title")?.split("\n")[0] || "";
        // The site uses a hash of the debug name in public ?m= links.
        const channel = identity(location.href).channel;
        const matchingCard = debugName && cardById.get(`${channel}:${publicId(debugName)}`);
        let url = matchingCard?.href;
        if (!url && debugName) {
          const parsed = new URL(location.href);
          parsed.searchParams.set("m", publicId(debugName));
          url = parsed.href;
        }
        if (!url && identity(location.href).mission_id) url = location.href;
        const item = url && record(url, text(title), debugName);
        if (!item) { lastError = "详情缺少任务标识，未合并；请导出后反馈页面情况。"; return; }
        const active = modal.querySelector(".detail-tab.active");
        const entry = tabEntries(modal).find((tab) => tab.element === active);
        const activeTab = text(active) || "unknown";
        // Community is excluded; Calculator exports only static basis fields.
        const allowed = entry && publicTab(entry.key);
        if (!allowed) return;
        const body = modal.querySelector(".detail-body");
        const calculator = entry.key === "calculator";
        const basis = calculator ? calculatorBasis(body) : null;
        appendUnique(item.detail_snapshots, {
          tab: activeTab,
          tab_key: entry.key,
          available_tabs: [...modal.querySelectorAll(".detail-tab")].map(text),
          header_text: text(modal.querySelector(".detail-header")),
          raw_text: calculator ? JSON.stringify(basis) : text(body),
          ...(calculator ? { calculator_basis: basis } : {}),
          sections: calculator ? [] : [...modal.querySelectorAll(".detail-body .detail-section")].filter(visible).map((section) => ({ heading: text(section.querySelector(".detail-section-title")), raw_text: text(section), links: linksWithin(section) })),
          links: !calculator && body ? linksWithin(body) : [],
          tooltips: !calculator && body ? [...body.querySelectorAll("[title]")].filter(visible).map((node) => ({ text: text(node), title: node.getAttribute("title") })) : [],
        });
      });
    } catch (error) { lastError = String(error.message || error); }
    const detailed = [...records.values()].filter((item) => item.detail_snapshots.length).length;
    const tabs = [...records.values()].reduce((sum, item) => sum + new Set(item.detail_snapshots.map((entry) => entry.value.tab)).size, 0);
    const message = `${records.size} 个任务 · ${detailed} 个有详情 · ${tabs} 个详情标签`;
    const status = panel.querySelector("[data-status]");
    const elapsed = automation ? (Date.now() - Date.parse(automation.started_at)) / 1000 : 0;
    const processed = automation ? automation.done + automation.failures.length : 0;
    const speed = elapsed > 0 && processed ? processed / elapsed : 0;
    const eta = speed ? ` · ${speed.toFixed(1)} 个/秒 · 预计剩余 ${Math.ceil((automation.total - processed) / speed / 60)} 分钟` : "";
    const progress = automation ? `\n自动采集 ${automation.done}/${automation.total} · 失败 ${automation.failures.length}${eta}` : "";
    const next = message + progress + `\n${clockWorker ? "后台定时器已启用" : "普通定时器（后台可能降速）"} · ${storageStatus}` + (lastError ? `\n${lastError}` : "");
    if (status.textContent !== next) status.textContent = next;
  }
  function schedule(event) {
    if (disposed || automation) return;
    if (event?.target && panel.contains(event.target)) return;
    clearTimeout(timer);
    timer = setTimeout(() => capture(!!automation), 350);
  }
  // Worker timers reduce ordinary hidden-tab timer throttling; browser freezing
  // and OS sleep can still suspend both the page and its worker.
  let clockWorker = null;
  let clockId = 0;
  const clockPending = new Map();
  try {
    if (typeof Worker !== "undefined") {
      const workerUrl = URL.createObjectURL(new Blob(["onmessage = (event) => { const {id, ms} = event.data; setTimeout(() => postMessage(id), ms); };"], { type: "text/javascript" }));
      clockWorker = new Worker(workerUrl);
      URL.revokeObjectURL(workerUrl);
      clockWorker.onmessage = (event) => { const entry = clockPending.get(event.data); if (entry) { clockPending.delete(event.data); entry.resolve(); } };
      clockWorker.onerror = () => {
        clockWorker?.terminate(); clockWorker = null;
        for (const entry of clockPending.values()) setTimeout(entry.resolve, entry.ms);
        clockPending.clear();
      };
    }
  } catch (_) { clockWorker = null; }
  const delay = (ms) => new Promise((resolve) => {
    if (!clockWorker) { setTimeout(resolve, ms); return; }
    const id = ++clockId;
    clockPending.set(id, { resolve, ms });
    clockWorker.postMessage({ id, ms });
  });
  const checkpointKey = () => JSON.stringify([identity(location.href).channel, new URL(location.href).searchParams.get("lang") || "", document.documentElement.lang]);
  function checkpointStore(write, value) {
    return new Promise((resolve, reject) => {
      if (typeof indexedDB === "undefined") { reject(Error("浏览器不支持 IndexedDB")); return; }
      const request = indexedDB.open("scmdb-public-mission-helper", 1);
      request.onupgradeneeded = () => request.result.createObjectStore("checkpoints");
      request.onerror = () => reject(request.error || Error("无法打开进度存储"));
      request.onblocked = () => reject(Error("进度存储被其他标签占用"));
      request.onsuccess = () => {
        const db = request.result;
        const transaction = db.transaction("checkpoints", write ? "readwrite" : "readonly");
        const store = transaction.objectStore("checkpoints");
        const operation = write ? store.put(value, checkpointKey()) : store.get(checkpointKey());
        let result;
        operation.onsuccess = () => { result = operation.result; };
        transaction.oncomplete = () => { db.close(); resolve(result); };
        transaction.onabort = transaction.onerror = () => { db.close(); reject(transaction.error || Error("保存失败")); };
      };
    });
  }
  async function saveCheckpoint() {
    if (checkpointBusy) return;
    checkpointBusy = true;
    try {
      await checkpointStore(true, { version: 4, saved_at: new Date().toISOString(), source_url: location.href, records: [...records], completed: [...completed] });
      storageStatus = `已保存 ${completed.size} 个完成任务 · ${new Date().toLocaleTimeString()}`;
    } catch (error) { storageStatus = `进度保存失败：${error.message}；请手动导出`; }
    finally { checkpointBusy = false; if (!disposed) capture(true); }
  }
  async function restoreCheckpoint() {
    if (automation || disposed) return;
    try {
      const saved = await checkpointStore(false);
      if (!saved || saved.version !== 4) throw Error("没有 v4 进度");
      for (const [key, item] of saved.records) {
        const current = records.get(key);
        if (!current) records.set(key, item);
        else {
          for (const kind of ["list_snapshots", "detail_snapshots"]) {
            for (const entry of item[kind]) if (!current[kind].some((existing) => existing.signature === entry.signature)) current[kind].push(entry);
          }
        }
      }
      for (const key of saved.completed) completed.add(key);
      storageStatus = `已恢复 ${completed.size} 个完成任务（${saved.saved_at}）；请确认游戏版本相同`;
    } catch (error) { storageStatus = `恢复失败：${error.message}`; }
    if (!disposed) capture(true);
  }
  async function waitFor(check, run) {
    for (let attempt = 0; attempt < 300; attempt += 1) {
      if (disposed || !run.active) throw Error("已停止");
      const value = check();
      if (value) return value;
      await delay(20);
    }
    throw Error("等待页面更新超时");
  }
  async function settle(run, expectedId, key) {
    let previous = "";
    let stable = 0;
    // Wait for two matching DOM samples rather than sleeping 1.2s per tab.
    for (let attempt = 0; attempt < 150; attempt += 1) {
      if (disposed || !run.active) throw Error("已停止");
      const current = currentModal();
      if (modalId(current) !== expectedId) throw Error("任务已被切换");
      const active = current.querySelector(".detail-tab.active");
      if (!tabEntries(current).some((tab) => tab.key === key && tab.element === active)) throw Error("详情标签已被切换");
      const body = current.querySelector(".detail-body");
      const content = body?.querySelector('[aria-busy="true"]') ? "" : text(body);
      stable = content && content === previous ? stable + 1 : 0;
      if (stable >= 2) return;
      previous = content;
      await delay(20);
    }
    throw Error("详情内容未稳定，保留为待重试");
  }
  function stopAutomation() {
    if (automation) automation.active = false;
  }
  async function startAutomation() {
    if (automation || disposed) return;
    if (currentModal()) { lastError = "请先关闭任务详情，再启动自动采集。"; capture(); return; }
    paused = false;
    panel.querySelector('[data-action="pause"]').textContent = "暂停";
    capture();
    const limit = Math.max(1, Math.min(5000, Number(panel.querySelector("[data-limit]").value) || 20));
    const queue = [...document.querySelectorAll("a.contract-card[href]")].filter(visible).map((card) => ({ href: card.href, ...identity(card.href) })).filter((item) => item.mission_id && !completed.has(`${item.channel}:${item.mission_id}`));
    const unique = [...new Map(queue.map((item) => [`${item.channel}:${item.mission_id}`, item])).values()].slice(0, limit);
    clearTimeout(timer);
    const run = { active: true, started_at: new Date().toISOString(), total: unique.length, done: 0, failures: [] };
    automation = run;
    runs.push(run);
    lastError = "";
    capture(true);
    try {
      for (const item of unique) {
        if (!run.active || disposed) break;
        try {
          const card = cardById.get(`${item.channel}:${item.mission_id}`);
          if (!card || !visible(card) || card.href !== item.href) throw Error("任务卡片已不在当前列表");
          card.click();
          let modal = await waitFor(() => { const candidate = currentModal(); return candidate && modalId(candidate) === item.mission_id && candidate; }, run);
          const keys = tabEntries(modal).filter((tab) => publicTab(tab.key)).map((tab) => tab.key);
          if (!keys.includes("overview") || !keys.includes("requirements")) throw Error("无法识别详情标签布局");
          for (const key of keys) {
            if (!run.active || disposed) break;
            modal = currentModal();
            if (modalId(modal) !== item.mission_id) throw Error("任务已被切换，停止本条采集");
            tabEntries(modal).find((tab) => tab.key === key).element.click();
            await waitFor(() => {
              const current = currentModal();
              const active = current?.querySelector(".detail-tab.active");
              return modalId(current) === item.mission_id && tabEntries(current).some((tab) => tab.key === key && tab.element === active);
            }, run);
            await settle(run, item.mission_id, key);
            if (!run.active || disposed) break;
            // Expand semantic disclosures only; never click arbitrary detail buttons
            // (favorites, completion, blueprint navigation, calculator, etc.).
            modal = currentModal();
            if (modalId(modal) !== item.mission_id) throw Error("任务已被切换");
            const disclosures = [...modal.querySelectorAll(".detail-body details:not([open]) > summary, .detail-body button[aria-expanded='false']")].filter(visible).slice(0, 100);
            for (const disclosure of disclosures) { if (!run.active || disposed) break; disclosure.click(); await delay(20); }
            if (disclosures.length) await settle(run, item.mission_id, key);
            if (run.active && !disposed) capture(true);
          }
          if (run.active && !disposed) {
            const saved = records.get(`${item.channel}:${item.mission_id}`);
            if (!keys.every((key) => saved?.detail_snapshots.some((entry) => entry.value.tab_key === key && entry.value.raw_text))) throw Error("详情标签内容未全部记录，保留为待重试");
            completed.add(`${item.channel}:${item.mission_id}`);
            run.done += 1;
            if (run.done % 25 === 0) await saveCheckpoint();
          }
        } catch (error) {
          if (!run.active || disposed) break;
          run.failures.push({ source_url: item.href, error: String(error.message || error) });
        }
        if (!run.active || disposed) break;
        const modal = currentModal();
        if (modal) {
          const close = modal.querySelector(".detail-close");
          if (!close) { lastError = "找不到详情关闭按钮，已停止；可以手动关闭后重试。"; break; }
          close.click();
          await waitFor(() => !currentModal(), run);
        }
        await delay(20);
        capture(true);
      }
    } catch (error) { lastError = String(error.message || error); }
    finally {
      run.stopped = !run.active;
      run.active = false;
      run.finished_at = new Date().toISOString();
      automation = null;
      if (!disposed) {
        lastError = lastError || `本批${run.stopped ? "已停止" : "结束"}：完成 ${run.done}/${run.total}，失败 ${run.failures.length}。请导出；再次启动将跳过本页会话中已完成的任务。`;
        capture(true);
        await saveCheckpoint();
        if (!run.stopped && run.done + run.failures.length === run.total && run.total > 0 && panel.querySelector("[data-auto-export]")?.checked) exportJson();
      }
    }
  }
  function exportJson() {
    capture(true);
    const missions = [...records.values()].map((item) => ({ ...item, list_snapshots: item.list_snapshots.map((entry) => entry.value), detail_snapshots: item.detail_snapshots.map((entry) => entry.value) }));
    const payload = { format: "scmdb-public-missions-capture-v1", helper_version: 5, source_url: location.href, started_at: startedAt, captured_at: new Date().toISOString(), page_language: document.documentElement.lang, note: "Public rendered DOM only. Optional user-started batches click existing cards/tabs/disclosures. Not a completeness claim. No Community content, calculator player inputs, app state, or direct /data/ requests by this helper. Text may be translated even if page_language is en.", warnings: lastError ? [lastError] : [], storage_status: storageStatus, automation_runs: runs, completed_mission_keys: [...completed], counts: { missions: missions.length, with_details: missions.filter((item) => item.detail_snapshots.length).length }, missions };
    const objectUrl = URL.createObjectURL(new Blob([JSON.stringify(payload, null, 2)], { type: "application/json" }));
    const link = document.createElement("a"); link.href = objectUrl; link.download = `scmdb-public-missions-${new Date().toISOString().replace(/[:.]/g, "-")}.json`; link.click(); setTimeout(() => URL.revokeObjectURL(objectUrl), 10000);
  }
  const panel = document.createElement("section");
  panel.setAttribute("aria-label", "SCMDB 任务采集助手");
  panel.style.cssText = "position:fixed;right:12px;bottom:12px;z-index:2147483647;width:min(340px,calc(100vw - 48px));padding:14px;border:1px solid #35d9e8;border-radius:12px;background:#071114;color:#e8f6f7;font:13px system-ui;box-shadow:0 8px 30px #0008";
  panel.innerHTML = '<strong>SCMDB 任务采集助手</strong><p>支持中文页面。自动采集会逐个打开当前列表的任务、切换公开详情标签并关闭；运行时请勿操作站点。不会自动翻页。普通折叠项会尝试展开。</p><label>本批任务数 <input data-limit type="number" min="1" max="5000" value="100" style="width:70px"></label><label><input data-auto-export type="checkbox" checked> 完成后自动导出</label><p data-status aria-live="polite">等待任务卡片</p><div><button data-action="auto">自动采集详情</button> <button data-action="stop">停止自动采集</button> <button data-action="save">保存进度</button> <button data-action="restore">恢复上次进度</button> <button data-action="capture">立即记录</button> <button data-action="pause">暂停</button> <button data-action="export">导出 JSON</button> <button data-action="close">关闭</button></div><small>每25个及批次结束自动保存到本浏览器。刷新后重新启动助手并恢复进度；须保持同一游戏版本。后台可跑，休眠或标签冻结会暂停；自动下载被拦截时手动导出。Calculator 仅采奖励、等级差额与规则；Community 不采集。非标准折叠项仍需手动展开。</small>';
  document.body.append(panel);
  panel.querySelectorAll("button").forEach((button) => { button.style.cssText = "margin-bottom:8px;padding:6px 8px;border:1px solid #2c7980;border-radius:5px;background:#10262a;color:#e8f6f7;cursor:pointer"; });
  panel.addEventListener("click", (event) => {
    const action = event.target.dataset.action;
    if (action === "auto") { startAutomation().catch((error) => { lastError = String(error.message || error); capture(); }); }
    if (action === "stop") { stopAutomation(); }
    if (action === "capture") { if (paused) { paused = false; panel.querySelector('[data-action="pause"]').textContent = "暂停"; } capture(); }
    if (action === "pause") { stopAutomation(); paused = !paused; event.target.textContent = paused ? "继续" : "暂停"; if (!paused) capture(); }
    if (action === "export") { exportJson(); }
    if (action === "save") { saveCheckpoint(); }
    if (action === "restore") { restoreCheckpoint(); }
    if (action === "close") { disposed = true; stopAutomation(); clockWorker?.terminate(); for (const entry of clockPending.values()) entry.resolve(); clockPending.clear(); observer.disconnect(); clearTimeout(timer); document.removeEventListener("click", schedule, true); window.removeEventListener("scroll", schedule, true); panel.remove(); delete window.__SCMDB_MISSIONS_CAPTURE__; }
  });
  const observer = new MutationObserver((mutations) => { if (mutations.some((mutation) => !panel.contains(mutation.target))) schedule(); });
  observer.observe(document.body, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ["class", "hidden", "aria-expanded"] });
  document.addEventListener("click", schedule, true);
  window.addEventListener("scroll", schedule, true);
  window.__SCMDB_MISSIONS_CAPTURE__ = { show: () => { panel.hidden = false; }, capture };
  capture();
})();
